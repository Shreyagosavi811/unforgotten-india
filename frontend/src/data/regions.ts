export function getRegionById(id: string): RegionDetail | undefined {
  const normalizedId = id.toUpperCase().trim();
  if (!normalizedId.startsWith('IN-')) {
    return REGIONS_DATA[`IN-${normalizedId}`];
  }
  return REGIONS_DATA[normalizedId];
}

export function getMvpRegions(): RegionDetail[] {
  return Object.values(REGIONS_DATA).filter((r) => r.isMvpAvailable);
}

export function getAllRegions(): RegionDetail[] {
  return Object.values(REGIONS_DATA);
}
